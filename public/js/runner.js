import { runModule, renderMarkdown, esc } from "./common.js";
import { sparkSVG } from "./claude-motion.js";

const busy = (text) => `${sparkSVG(16, "spark--busy")} ${text}`;

// Wires Run / Sample buttons to a streamed module run and renders the output.
export function attachRunner({ moduleId, getInput, runBtn, sampleBtn, output, empty, status, wrap, onStart, onComplete }) {
  let controller = null;
  let text = "";
  let frame = 0;

  const paint = () => {
    frame = 0;
    renderMarkdown(output, text);
  };

  function setStatus(html) {
    status.innerHTML = html;
  }

  async function run(demo) {
    controller?.abort();
    controller = new AbortController();
    text = "";
    empty.hidden = true;
    output.hidden = false;
    output.innerHTML = "";
    runBtn.disabled = true;
    sampleBtn.disabled = true;
    onStart?.();
    setStatus(busy("Claude is working…"));
    output.classList.add("is-streaming");
    const started = performance.now();

    try {
      const done = await runModule(moduleId, getInput(), {
        demo,
        signal: controller.signal,
        onMeta: (m) => {
          if (m.mode === "demo") setStatus(busy("Replaying sample output…"));
        },
        onText: (t) => {
          text += t;
          frame ||= requestAnimationFrame(paint);
        },
      });
      cancelAnimationFrame(frame);
      paint();
      const secs = ((performance.now() - started) / 1000).toFixed(1);
      setStatus(done.model === "sample output" ? `Sample output · ${secs}s` : `Generated by ${esc(done.model)} · ${secs}s`);
      onComplete?.(text, done);
    } catch (err) {
      if (err.name === "AbortError") return;
      cancelAnimationFrame(frame);
      if (text) paint();
      output.insertAdjacentHTML(
        "beforeend",
        `<div class="error-box">${esc(err.message)} You can use <strong>Play sample output</strong> to continue the demo.</div>`,
      );
      setStatus("Stopped");
    } finally {
      output.classList.remove("is-streaming");
      runBtn.disabled = false;
      sampleBtn.disabled = false;
      wrap?.scrollTo?.({ top: 0 });
    }
  }

  runBtn.addEventListener("click", () => run(false));
  sampleBtn.addEventListener("click", () => run(true));

  return {
    show(md, note) {
      text = md;
      empty.hidden = true;
      output.hidden = false;
      paint();
      setStatus(esc(note));
    },
  };
}
